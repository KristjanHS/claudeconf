#!/usr/bin/env python3
"""Measured context-cost block: every number parsed from the repo's own files.

Usage: context_cost.py --readme FILE [--root DIR] [--check].
Writes the table between the context-cost markers in FILE; `--check` writes
nothing. Exit 0 ok/fresh, 1 stale block (--check), 2 input error — a missing
source file or a regex that no longer matches is an error, never a guessed value.
"""

from __future__ import annotations

import argparse
import datetime as dt
import re
import sys
from dataclasses import dataclass
from pathlib import Path

# Sibling import that survives `python3 -I` and by-path importlib loads (tests).
sys.path.insert(0, str(Path(__file__).resolve().parent))
from marker_block import MarkerError, has_markers, replace_between  # noqa: E402

BLOCK_MARKERS = ("<!-- context-cost:start -->", "<!-- context-cost:end -->")
BYTES_PER_TOKEN = 4
POINTER_RE = re.compile(r"(rules|references)/[\w.-]+\.md")
GENERATED_RE = re.compile(
    r"^<sub>Generated by `.*` on (\d{4}-\d{2}-\d{2})</sub>$", re.M
)

STATUSLINE = ".claude/statusline.sh"
BUDGET_HOOK = ".claude/hooks/impag-budget-check.py"
# name -> (source file, regex with one integer group)
PARSED: dict[str, tuple[str, str]] = {
    "window": (STATUSLINE, r"^WINDOW=(\d+)$"),
    "stop_pct": (STATUSLINE, r"^STOP_PCT=(\d+)$"),
    "yellow": (STATUSLINE, r'-ge (\d+) \]; then COLOR="\$YELLOW"'),
    "red": (STATUSLINE, r'-ge (\d+) \]; then COLOR="\$RED"'),
    "margin": (STATUSLINE, r'"\$REMAIN_TO_STOP" -le (\d+) \]'),
    "hard_stop": (BUDGET_HOOK, r"^HARD_STOP_TOKENS = ([\d_]+)$"),
}
BANDS_RE = re.compile(r"^BANDS: .*?= \($(.*?)^\)$", re.M | re.S)
SOFT_RE = re.compile(r'\(\s*([\d_]+),\s*"soft"')


class InputError(Exception):
    """Bad input: exit 2."""


@dataclass(frozen=True)
class Row:
    metric: str
    value: str
    source: str


def _read(root: Path, rel: str) -> str:
    try:
        return (root / rel).read_bytes().decode("utf-8")
    except (OSError, UnicodeDecodeError) as e:
        raise InputError(f"cannot read {root / rel}: {e}") from e


def _md_files(root: Path, rel: str) -> list[Path]:
    d = root / rel
    if not d.is_dir():
        raise InputError(f"missing directory {d}")
    return sorted(p for p in d.glob("*.md") if p.is_file())


def _int(root: Path, rel: str, pattern: str) -> int:
    hits = re.findall(pattern, _read(root, rel), re.M)
    if len(hits) != 1:
        raise InputError(f"{rel}: /{pattern}/ matched {len(hits)} times, need 1")
    return int(hits[0].replace("_", ""))


def _soft_bands(root: Path) -> list[int]:
    block = BANDS_RE.search(_read(root, BUDGET_HOOK))
    bands = (
        [int(b.replace("_", "")) for b in SOFT_RE.findall(block[1])] if block else []
    )
    if not bands:
        raise InputError(f"{BUDGET_HOOK}: no soft entries in BANDS")
    return bands


def _n(v: int) -> str:
    return f"{v:,}"


def collect(root: Path) -> list[Row]:
    rules = _md_files(root, ".claude/rules")
    refs = _md_files(root, ".claude/references")
    rule_b = sum(p.stat().st_size for p in rules)
    ref_b = sum(p.stat().st_size for p in refs)
    deferred = rule_b + ref_b
    claude_md = _read(root, ".claude/CLAUDE.md")
    pointers = sum(1 for line in claude_md.splitlines() if POINTER_RE.search(line))
    v = {k: _int(root, rel, pat) for k, (rel, pat) in PARSED.items()}
    soft = _soft_bands(root)
    for kind in ("skills", "hooks"):
        if not (root / ".claude" / kind).is_dir():
            raise InputError(f"missing directory {root / '.claude' / kind}")
    skill_dir = root / ".claude/skills"
    skills = sum(1 for p in skill_dir.iterdir() if p.is_dir() and p.name[0] != ".")
    hooks = sum(1 for p in (root / ".claude/hooks").glob("*.py") if p.is_file())
    sl, hk = f"`{STATUSLINE}`", f"`{BUDGET_HOOK}`"
    return [
        Row("Path-gated rules", _n(len(rules)), "`.claude/rules/*.md`"),
        Row("Rule bytes", _n(rule_b), "sum of `.claude/rules/*.md`"),
        Row("L3 references", _n(len(refs)), "`.claude/references/*.md`"),
        Row("Reference bytes", _n(ref_b), "sum of `.claude/references/*.md`"),
        Row("Deferred bytes", _n(deferred), "rule bytes + reference bytes"),
        Row(
            "Deferred tokens (est.)",
            "~" + _n(deferred // BYTES_PER_TOKEN),
            f"deferred bytes / BYTES_PER_TOKEN ({BYTES_PER_TOKEN})",
        ),
        Row(
            "`CLAUDE.md` bytes",
            _n(len(claude_md.encode("utf-8"))),
            "`.claude/CLAUDE.md`",
        ),
        Row(
            "Pointer lines in `CLAUDE.md`",
            _n(pointers),
            f"lines matching `{POINTER_RE.pattern}` in `.claude/CLAUDE.md`",
        ),
        Row("Statusline budget window", _n(v["window"]), f"`WINDOW=` in {sl}"),
        Row("Statusline session stop", f"{v['stop_pct']}%", f"`STOP_PCT=` in {sl}"),
        Row("Statusline amber at", _n(v["yellow"]), f"`$YELLOW` threshold in {sl}"),
        Row("Statusline red at", _n(v["red"]), f"`$RED` threshold in {sl}"),
        Row(
            "`/clear soon` margin",
            _n(v["margin"]),
            f"`REMAIN_TO_STOP -le` in {sl}",
        ),
        Row("Budget hard stop", _n(v["hard_stop"]), f"`HARD_STOP_TOKENS` in {hk}"),
        Row(
            "Budget soft bands",
            " / ".join(map(_n, soft)),
            f'`"soft"` entries of `BANDS` in {hk}',
        ),
        Row("Skills", _n(skills), "`.claude/skills/*/`"),
        Row("Hooks", _n(hooks), "`.claude/hooks/*.py`"),
    ]


def _row(cells: list[str]) -> str:
    """GFM splits a cell on `|` even inside backticks, so escape it."""
    return "| " + " | ".join(c.replace("|", r"\|") for c in cells) + " |"


def render_block(rows: list[Row], command: str, date: str) -> str:
    lines = ["| Metric | Value | Source |", "|---|---|---|"]
    lines += [_row([r.metric, r.value, r.source]) for r in rows]
    lines += ["", f"<sub>Generated by `{command}` on {date}</sub>"]
    return "\n".join(lines) + "\n"


def command_for(readme: Path, root: Path) -> str:
    """The write command as run from the repo root — stable whatever the caller's cwd."""
    try:
        rel = readme.resolve().relative_to(root.resolve()).as_posix()
    except ValueError:
        rel = str(readme)
    return f"python3 scripts/context_cost.py --readme {rel}"


def run(readme: Path, root: Path, check: bool, today: str) -> int:
    try:
        text = readme.read_bytes().decode("utf-8")
    except (OSError, UnicodeDecodeError) as e:
        raise InputError(f"cannot read {readme}: {e}") from e
    if not has_markers(text, BLOCK_MARKERS):
        raise InputError(f"{readme}: no {BLOCK_MARKERS[0]} markers")
    try:
        replace_between(text, *BLOCK_MARKERS, "")  # validates the pair only
    except MarkerError as e:
        raise InputError(f"{readme}: {e}") from e
    rows = collect(root)
    command = command_for(readme, root)
    # The date alone never makes a block stale: reuse the one already written.
    inner = text.split(BLOCK_MARKERS[0], 1)[1].split(BLOCK_MARKERS[1], 1)[0]
    old = GENERATED_RE.search(inner)
    same_day = replace_between(
        text, *BLOCK_MARKERS, render_block(rows, command, old[1] if old else today)
    )
    if same_day == text:
        return 0
    if check:
        print(f"stale: {readme}", file=sys.stderr)
        return 1
    fresh = replace_between(text, *BLOCK_MARKERS, render_block(rows, command, today))
    try:
        readme.write_bytes(fresh.encode("utf-8"))
    except OSError as e:
        raise InputError(f"cannot write {readme}: {e}") from e
    print(f"updated: {readme}", file=sys.stderr)
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description="Measured context-cost block for a README."
    )
    ap.add_argument("--readme", required=True, type=Path)
    ap.add_argument(
        "--root", type=Path, default=Path("."), help="repo root (default: cwd)"
    )
    ap.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if the block is stale; write nothing",
    )
    args = ap.parse_args(argv)
    try:
        return run(args.readme, args.root, args.check, dt.date.today().isoformat())
    except InputError as e:
        print(f"error: {e}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
