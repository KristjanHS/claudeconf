#!/usr/bin/env python3
"""Public adoption signals block: stars, forks, watchers and clone traffic from `gh api`.

Usage: adoption_signals.py --readme FILE --repo OWNER/NAME [--from-json DIR]
       [--check] [--max-age-days N].
Writes the table between the adoption markers in FILE. Any `gh` failure (no
auth, 403 on traffic, bad JSON, missing field) is exit 2 with FILE untouched —
never a block of zeros. `--from-json DIR` reads DIR/repo.json + DIR/clones.json
instead of calling `gh`. A metric whose value is 0 gets no row. `--check`
writes nothing and calls nothing: exit 1 when the block's "on YYYY-MM-DD" is
older than --max-age-days (or missing).
Exit 0 ok/fresh, 1 stale (--check), 2 input error.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import re
import subprocess
import sys
from pathlib import Path
from typing import Any

# Sibling import that survives `python3 -I` and by-path importlib loads (tests).
sys.path.insert(0, str(Path(__file__).resolve().parent))
from marker_block import MarkerError, has_markers, replace_between  # noqa: E402

BLOCK_MARKERS = ("<!-- adoption:start -->", "<!-- adoption:end -->")
REPO_RE = re.compile(r"^[\w.-]+/[\w.-]+$")
GENERATED_RE = re.compile(
    r"^<sub>Generated by `.*` on (\d{4}-\d{2}-\d{2})</sub>$", re.M
)
DEFAULT_MAX_AGE_DAYS = 30
GH_TIMEOUT_S = 30

# metric -> (endpoint key, JSON field, source note)
METRICS: tuple[tuple[str, str, str, str], ...] = (
    ("Stars", "repo", "stargazers_count", ""),
    ("Forks", "repo", "forks_count", ""),
    ("Watchers", "repo", "subscribers_count", ""),
    ("Clones (14 days)", "clones", "count", " (14-day window)"),
    ("Unique cloners (14 days)", "clones", "uniques", " (14-day window)"),
)


class InputError(Exception):
    """Bad input or a failed fetch: exit 2, README untouched."""


def endpoints(repo: str) -> dict[str, str]:
    return {"repo": f"repos/{repo}", "clones": f"repos/{repo}/traffic/clones"}


def _gh_json(endpoint: str) -> Any:
    try:
        proc = subprocess.run(
            ["gh", "api", endpoint],
            capture_output=True,
            text=True,
            timeout=GH_TIMEOUT_S,
            check=False,
        )
    except (OSError, subprocess.TimeoutExpired) as e:
        raise InputError(f"gh api {endpoint}: {e}") from e
    if proc.returncode != 0:
        msg = proc.stderr.strip() or f"exit {proc.returncode}"
        raise InputError(f"gh api {endpoint}: {msg}")
    try:
        return json.loads(proc.stdout)
    except json.JSONDecodeError as e:
        raise InputError(f"gh api {endpoint}: bad JSON: {e}") from e


def _file_json(path: Path) -> Any:
    try:
        return json.loads(path.read_bytes().decode("utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as e:
        raise InputError(f"cannot load {path}: {e}") from e


def fetch(repo: str, from_json: Path | None) -> dict[str, Any]:
    eps = endpoints(repo)
    if from_json is not None:
        return {k: _file_json(from_json / f"{k}.json") for k in eps}
    return {k: _gh_json(ep) for k, ep in eps.items()}


def collect(repo: str, payloads: dict[str, Any]) -> list[tuple[str, str, str]]:
    eps = endpoints(repo)
    rows = []
    for metric, key, field, note in METRICS:
        doc = payloads.get(key)
        v = doc.get(field) if isinstance(doc, dict) else None
        # bool is an int subclass; a missing/odd field is an error, never a 0.
        if not isinstance(v, int) or isinstance(v, bool) or v < 0:
            raise InputError(f"{eps[key]}: field {field!r} missing or not a count")
        if v == 0:
            continue  # zero rows are omitted (validated first, so never a silent gap)
        rows.append((metric, f"{v:,}", f"`{field}` from `gh api {eps[key]}`{note}"))
    return rows


def _row(cells: tuple[str, ...]) -> str:
    """GFM splits a cell on `|` even inside backticks, so escape it."""
    return "| " + " | ".join(c.replace("|", r"\|") for c in cells) + " |"


def render_block(rows: list[tuple[str, str, str]], command: str, date: str) -> str:
    lines = ["| Metric | Value | Source |", "|---|---|---|"]
    lines += [_row(r) for r in rows]
    lines += ["", f"<sub>Generated by `{command}` on {date}</sub>"]
    return "\n".join(lines) + "\n"


def command_for(readme: Path, repo: str, from_json: Path | None) -> str:
    cmd = f"python3 scripts/adoption_signals.py --readme {readme} --repo {repo}"
    return cmd + (f" --from-json {from_json}" if from_json is not None else "")


def _read_readme(readme: Path) -> str:
    try:
        text = readme.read_bytes().decode("utf-8")
    except (OSError, UnicodeDecodeError) as e:
        raise InputError(f"cannot read {readme}: {e}") from e
    if not has_markers(text, BLOCK_MARKERS):
        raise InputError(f"{readme}: no {BLOCK_MARKERS[0]} markers")
    return text


def check(readme: Path, max_age_days: int, today: dt.date) -> int:
    text = _read_readme(readme)
    try:
        replace_between(text, *BLOCK_MARKERS, "")  # validates the pair only
    except MarkerError as e:
        raise InputError(f"{readme}: {e}") from e
    inner = text.split(BLOCK_MARKERS[0], 1)[1].split(BLOCK_MARKERS[1], 1)[0]
    m = GENERATED_RE.search(inner)
    if not m:
        print(f"stale: {readme}: no generated date in block", file=sys.stderr)
        return 1
    try:
        age = (today - dt.date.fromisoformat(m[1])).days
    except ValueError as e:
        raise InputError(f"{readme}: bad generated date {m[1]}: {e}") from e
    if age > max_age_days:
        print(f"stale: {readme}: block is {age} days old", file=sys.stderr)
        return 1
    return 0


def write(readme: Path, repo: str, from_json: Path | None, today: dt.date) -> int:
    text = _read_readme(readme)
    # Fetch fully before touching the file: a failure raises here, README untouched.
    rows = collect(repo, fetch(repo, from_json))
    block = render_block(rows, command_for(readme, repo, from_json), today.isoformat())
    try:
        fresh = replace_between(text, *BLOCK_MARKERS, block)
    except MarkerError as e:
        raise InputError(f"{readme}: {e}") from e
    if fresh != text:
        try:
            readme.write_bytes(fresh.encode("utf-8"))
        except OSError as e:
            raise InputError(f"cannot write {readme}: {e}") from e
        print(f"updated: {readme}", file=sys.stderr)
    return 0


def main(argv: list[str] | None = None, today: dt.date | None = None) -> int:
    ap = argparse.ArgumentParser(description="Public adoption signals for a README.")
    ap.add_argument("--readme", required=True, type=Path)
    ap.add_argument("--repo", required=True, help="OWNER/NAME")
    ap.add_argument(
        "--from-json",
        type=Path,
        metavar="DIR",
        help="read DIR/repo.json + DIR/clones.json instead of calling gh",
    )
    ap.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if the block is older than --max-age-days; write nothing",
    )
    ap.add_argument("--max-age-days", type=int, default=DEFAULT_MAX_AGE_DAYS)
    args = ap.parse_args(argv)
    today = today or dt.date.today()
    try:
        if not REPO_RE.match(args.repo):
            raise InputError(f"--repo {args.repo!r}: want OWNER/NAME")
        if args.check:
            return check(args.readme, args.max_age_days, today)
        return write(args.readme, args.repo, args.from_json, today)
    except InputError as e:
        print(f"error: {e}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
