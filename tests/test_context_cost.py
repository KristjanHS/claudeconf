"""scripts/context_cost.py against a throwaway fixture repo."""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

import pytest

from conftest import REPO_ROOT

_spec = importlib.util.spec_from_file_location(
    "context_cost", REPO_ROOT / "scripts" / "context_cost.py"
)
assert _spec is not None and _spec.loader is not None
cc = importlib.util.module_from_spec(_spec)
sys.modules["context_cost"] = cc
_spec.loader.exec_module(cc)

START, END = cc.BLOCK_MARKERS

STATUSLINE = """\
WINDOW=300000
STOP_PCT=75
if   [ "$USED_TOK" -ge 240000 ]; then COLOR="$RED"
elif [ "$USED_TOK" -ge 200000 ]; then COLOR="$YELLOW"
else                                  COLOR="$GREEN"; fi
if [ "$REMAIN_TO_STOP" -le 30000 ]; then
"""

HOOK = """\
HARD_STOP_TOKENS = 200_000
BANDS: tuple[tuple[int, str, str], ...] = (
    (
        120_000,
        "soft",
        "fyi",
    ),
    (150_000, "soft", "fyi"),
    (
        HARD_STOP_TOKENS,
        "hard",
        "stop",
    ),
)
SUBAGENT_BANDS: tuple[tuple[int, str, str], ...] = (
    (99_000, "soft", "not a main band"),
)
"""

FILES = {
    ".claude/rules/a.md": "a" * 1000,
    ".claude/rules/b.md": "b" * 200,
    ".claude/rules/notes.txt": "ignored",
    ".claude/references/r.md": "r" * 2800,
    ".claude/CLAUDE.md": (
        "# x\n"
        "- `~/.claude/references/r.md` - one\n"
        "- `rules/a.md` and `rules/b.md` - two on one line\n"
        "- references/nope.txt is not a pointer\n"
    ),
    ".claude/statusline.sh": STATUSLINE,
    ".claude/hooks/impag-budget-check.py": HOOK,
    ".claude/hooks/other.py": "",
    ".claude/hooks/README.md": "",
    ".claude/skills/s1/SKILL.md": "",
    ".claude/skills/s2/SKILL.md": "",
    ".claude/skills/.hidden/SKILL.md": "",
    ".claude/skills/stray.md": "",
}

README = f"# r\n\nintro\n{START}\nold\n{END}\ntail\n"

EXPECTED = """\
| Metric | Value | Source |
|---|---|---|
| Path-gated rules | 2 | `.claude/rules/*.md` |
| Rule bytes | 1,200 | sum of `.claude/rules/*.md` |
| L3 references | 1 | `.claude/references/*.md` |
| Reference bytes | 2,800 | sum of `.claude/references/*.md` |
| Deferred bytes | 4,000 | rule bytes + reference bytes |
| Deferred tokens (est.) | ~1,000 | deferred bytes / BYTES_PER_TOKEN (4) |
| `CLAUDE.md` bytes | 129 | `.claude/CLAUDE.md` |
| Pointer lines in `CLAUDE.md` | 2 | lines matching `(rules\\|references)/[\\w.-]+\\.md` in `.claude/CLAUDE.md` |
| Statusline budget window | 300,000 | `WINDOW=` in `.claude/statusline.sh` |
| Statusline session stop | 75% | `STOP_PCT=` in `.claude/statusline.sh` |
| Statusline amber at | 200,000 | `$YELLOW` threshold in `.claude/statusline.sh` |
| Statusline red at | 240,000 | `$RED` threshold in `.claude/statusline.sh` |
| `/clear soon` margin | 30,000 | `REMAIN_TO_STOP -le` in `.claude/statusline.sh` |
| Budget hard stop | 200,000 | `HARD_STOP_TOKENS` in `.claude/hooks/impag-budget-check.py` |
| Budget soft bands | 120,000 / 150,000 | `"soft"` entries of `BANDS` in `.claude/hooks/impag-budget-check.py` |
| Skills | 2 | `.claude/skills/*/` |
| Hooks | 2 | `.claude/hooks/*.py` |

<sub>Generated by `python3 scripts/context_cost.py --readme README.md` on 2026-01-02</sub>
"""


@pytest.fixture
def repo(tmp_path: Path) -> Path:
    for rel, body in {**FILES, "README.md": README}.items():
        (tmp_path / rel).parent.mkdir(parents=True, exist_ok=True)
        (tmp_path / rel).write_text(body)
    return tmp_path


def cli(repo: Path, *extra: str) -> int:
    return cc.main(["--readme", str(repo / "README.md"), "--root", str(repo), *extra])


def test_writes_exact_table(repo: Path):
    assert len(FILES[".claude/CLAUDE.md"].encode()) == 129
    assert cc.run(repo / "README.md", repo, check=False, today="2026-01-02") == 0
    text = (repo / "README.md").read_text()
    assert text == f"# r\n\nintro\n{START}\n{EXPECTED}{END}\ntail\n"


def test_check_fresh_is_0_and_writes_nothing(repo: Path):
    assert cli(repo) == 0
    before = (repo / "README.md").read_bytes()
    assert cli(repo, "--check") == 0
    assert (repo / "README.md").read_bytes() == before


def test_check_stale_after_rule_grows_is_1(repo: Path, capsys):
    assert cli(repo) == 0
    rule = repo / ".claude/rules/a.md"
    rule.write_text(rule.read_text() + "x" * 1024)
    before = (repo / "README.md").read_bytes()
    assert cli(repo, "--check") == 1
    assert "stale:" in capsys.readouterr().err
    assert (repo / "README.md").read_bytes() == before


def test_date_alone_is_not_stale(repo: Path):
    assert cc.run(repo / "README.md", repo, check=False, today="2020-01-01") == 0
    assert cc.run(repo / "README.md", repo, check=True, today="2026-01-02") == 0


def test_write_refreshes_date_only_when_numbers_change(repo: Path):
    readme = repo / "README.md"
    cc.run(readme, repo, check=False, today="2020-01-01")
    cc.run(readme, repo, check=False, today="2026-01-02")
    assert "on 2020-01-01</sub>" in readme.read_text()
    (repo / ".claude/rules/c.md").write_text("c")
    cc.run(readme, repo, check=False, today="2026-01-02")
    assert "on 2026-01-02</sub>" in readme.read_text()


def test_renamed_window_is_2(repo: Path, capsys):
    sl = repo / ".claude/statusline.sh"
    sl.write_text(sl.read_text().replace("WINDOW=", "BUDGET_WINDOW="))
    assert cli(repo, "--check") == 2
    assert "WINDOW" in capsys.readouterr().err


@pytest.mark.parametrize(
    ("rel", "old", "new"),
    [
        (".claude/statusline.sh", 'COLOR="$YELLOW"', 'COLOR="$AMBER"'),
        (".claude/statusline.sh", "-le 30000", "-lt 30000"),
        (".claude/hooks/impag-budget-check.py", "HARD_STOP_TOKENS = ", "HARD_STOP = "),
        (".claude/hooks/impag-budget-check.py", '"soft"', '"info"'),
        (".claude/hooks/impag-budget-check.py", "BANDS: ", "MAIN_BANDS: "),
    ],
)
def test_regex_miss_is_2(repo: Path, rel: str, old: str, new: str):
    path = repo / rel
    assert old in path.read_text()
    path.write_text(path.read_text().replace(old, new))
    assert cli(repo, "--check") == 2


def test_duplicate_constant_is_2(repo: Path):
    sl = repo / ".claude/statusline.sh"
    sl.write_text(sl.read_text() + "WINDOW=1\n")
    assert cli(repo) == 2


@pytest.mark.parametrize(
    "rel", [".claude/statusline.sh", ".claude/CLAUDE.md", ".claude/references/r.md"]
)
def test_missing_source_is_2(repo: Path, rel: str):
    (repo / rel).unlink()
    if rel.endswith("r.md"):
        (repo / ".claude/references").rmdir()
    assert cli(repo) == 2


def test_missing_markers_is_2(repo: Path, capsys):
    (repo / "README.md").write_text("# r\nno block\n")
    assert cli(repo, "--check") == 2
    assert cli(repo) == 2
    assert "markers" in capsys.readouterr().err
    assert (repo / "README.md").read_text() == "# r\nno block\n"


def test_half_marker_pair_is_2(repo: Path):
    (repo / "README.md").write_text(f"# r\n{START}\nbody\n")
    assert cli(repo) == 2


def test_end_marker_only_is_2(repo: Path):
    (repo / "README.md").write_text(f"# r\n{END}\nbody\n")
    assert cli(repo, "--check") == 2
    assert cli(repo) == 2


def test_real_repo_sources_parse():
    """The live statusline/hook still match every regex (a rename fails here first)."""
    rows = {r.metric: r.value for r in cc.collect(REPO_ROOT)}
    assert rows["Statusline budget window"].replace(",", "").isdigit()
    assert rows["Budget soft bands"]
